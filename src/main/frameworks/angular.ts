import type { DesignSystem } from "@shared/types";
import type { FrameworkKit } from "./types";

/** Global stylesheet generated next to the setup file; the template's angular.json lists it. */
export const ANGULAR_STYLES_FILE = "src/design-system.css";

export const angularKit: FrameworkKit = {
  id: "angular",
  label: "Angular",
  sourceExtensions: [".ts", ".html"],
  defaultSetupPath: "src/app/design-system.ts",
  // `ng` asks about analytics on first run, which would hang a non-interactive server.
  env: { NG_CLI_ANALYTICS: "false" },

  usage: (c) =>
    `import { ${c.angularImport ?? c.name} } from "${c.importPath}"; imports: [${c.angularImport ?? c.name}]; <${c.selector ?? c.name}>`,

  setupFiles: (ds, mainPath) => ({ [mainPath]: angularSetup(ds), [ANGULAR_STYLES_FILE]: angularStyles(ds) }),

  setupRules: (ds, mainPath) =>
    `- ${mainPath} (root providers) and ${ANGULAR_STYLES_FILE} (global styles) are generated from the ${ds.name} setup and already wired into the app. Do not edit them, and do not add the design system styles again.
- Every standalone component that uses a ${ds.name} component must list it (or its NgModule) in its \`imports\` array. In an NgModule app, add it to the \`imports\` of the NgModule that declares the component instead.`,
};

export function angularSetup(ds: DesignSystem): string {
  const modules = ds.setup.angularModules ?? [];
  const providers = ds.setup.angularProviders ?? [];
  const byPath = new Map<string, string[]>();
  for (const m of [...modules, ...providers.flatMap((p) => p.imports)]) {
    const names = byPath.get(m.importPath) ?? [];
    if (!names.includes(m.importName)) byPath.set(m.importPath, [...names, m.importName]);
  }
  const entries = [...(modules.length ? [`importProvidersFrom(${modules.map((m) => m.importName).join(", ")})`] : []), ...providers.map((p) => p.expression)];
  return `// Generated by Atelier from the ${ds.name} design system setup. Do not edit.
import { importProvidersFrom, type EnvironmentProviders, type Provider } from "@angular/core";
${[...byPath].map(([from, names]) => importLine(names, from)).join("\n")}

/** App-wide providers from the design system, added in app.config.ts. */
export const designSystemProviders: (Provider | EnvironmentProviders)[] = [${entries.join(", ")}];
`;
}

/** `default as Aura` becomes a default import; other names are named imports. */
function importLine(names: string[], from: string): string {
  const def = names.find((n) => n.startsWith("default as "))?.slice("default as ".length);
  const named = names.filter((n) => !n.startsWith("default as "));
  const parts = [def, named.length ? `{ ${named.join(", ")} }` : undefined].filter(Boolean);
  return `import ${parts.join(", ")} from "${from}";`;
}

export function angularStyles(ds: DesignSystem): string {
  return `/* Generated by Atelier from the ${ds.name} design system setup. Do not edit. */
${ds.setup.globalCss.map((spec) => `@import "${spec}";`).join("\n")}
`;
}
