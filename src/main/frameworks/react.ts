import type { DesignSystem } from "@shared/types";
import type { FrameworkKit } from "./types";

export const reactKit: FrameworkKit = {
  id: "react",
  label: "React",
  sourceExtensions: [".tsx", ".ts", ".jsx", ".js"],
  defaultSetupPath: "src/design-system/DesignSystemRoot.tsx",

  usage(c) {
    const [root] = c.name.split(".");
    return `import ${c.defaultExport ? root : `{ ${root} }`} from "${c.importPath}"; <${c.name} />`;
  },

  setupFiles: (ds, mainPath) => ({ [mainPath]: reactSetup(ds) }),

  setupRules: (ds, mainPath) =>
    `- ${mainPath} is generated from the ${ds.name} setup and is already rendered around the app root. Do not edit it, and do not import the design system stylesheet or provider again.`,
};

/** Regenerated whenever the design system setup changes. */
export function reactSetup(ds: DesignSystem): string {
  const css = ds.setup.globalCss.map((spec) => `import "${spec}";`).join("\n");
  const provider = ds.setup.provider;
  const providerImport = provider ? `import { ${provider.importName} } from "${provider.importPath}";\n` : "";
  const body = provider
    ? `<${provider.importName}${provider.props ? ` ${provider.props}` : ""}>{children}</${provider.importName}>`
    : "<>{children}</>";
  return `// Generated by Atelier from the ${ds.name} design system setup. Do not edit.
import type { ReactNode } from "react";
${css}
${providerImport}
export default function DesignSystemRoot({ children }: { children: ReactNode }) {
  return ${body};
}
`;
}
