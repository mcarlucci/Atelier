import type { DesignSystem } from "@shared/types";
import type { FrameworkKit } from "./types";

export const vueKit: FrameworkKit = {
  id: "vue",
  label: "Vue",
  sourceExtensions: [".vue", ".ts", ".tsx", ".js"],
  defaultSetupPath: "src/design-system/setup.ts",

  usage: (c) => `import ${c.defaultExport ? c.name : `{ ${c.name} }`} from "${c.importPath}"; <${c.name} />`,

  setupFiles: (ds, mainPath) => ({ [mainPath]: vueSetup(ds) }),

  setupRules: (ds, mainPath) =>
    `- ${mainPath} is generated from the ${ds.name} setup. It installs the design system's styles${ds.setup.vuePlugin ? " and plugin" : ""} and provides <DesignSystemRoot>, which already wraps the app. Do not edit it, and do not import the design system stylesheet or plugin again.`,
};

/**
 * Exports `installDesignSystem(app)` (styles and plugin) and a
 * `DesignSystemRoot` component that wraps the app in the provider, if any.
 */
export function vueSetup(ds: DesignSystem): string {
  const { provider, vuePlugin, globalCss } = ds.setup;
  const imports = new Map<string, Set<string>>();
  const add = (name: string, from: string) => imports.set(from, (imports.get(from) ?? new Set()).add(name));
  if (vuePlugin) add(vuePlugin.importName, vuePlugin.importPath);
  for (const extra of vuePlugin?.imports ?? []) add(extra.importName, extra.importPath);
  if (provider) add(provider.importName, provider.importPath);
  const importLines = [...imports].map(([from, names]) => `import { ${[...names].join(", ")} } from "${from}";`).join("\n");
  const options = vuePlugin?.options?.trim();
  // `default as PrimeVue` binds `PrimeVue`.
  const plugin = vuePlugin?.importName.split(/\s+as\s+/).pop();
  const use = vuePlugin
    ? vuePlugin.factory
      ? `  app.use(${plugin}(${options ?? ""}));`
      : `  app.use(${plugin}${options ? `, ${options}` : ""});`
    : "  // The design system has no Vue plugin to install.";
  const render = provider ? `h(${provider.importName}, ${attrsToObject(provider.props)}, slots)` : "slots.default?.()";
  return `// Generated by Atelier from the ${ds.name} design system setup. Do not edit.
import { defineComponent, h, type App } from "vue";
${globalCss.map((spec) => `import "${spec}";`).join("\n")}
${importLines}

/** Installs the design system on the app. Called once in main.ts. */
export function installDesignSystem(app: App): void {
${use}
}

/** Wraps the whole app${provider ? ` in <${provider.importName}>` : ""}. */
export const DesignSystemRoot = defineComponent({
  name: "DesignSystemRoot",
  setup(_props, { slots }) {
    return () => ${render};
  },
});
`;
}

/** `appearance="light" scaling={1}` (the provider props field) -> `{ appearance: "light", scaling: 1 }`. */
export function attrsToObject(props?: string): string {
  if (!props?.trim()) return "null";
  const entries = [...props.matchAll(/([A-Za-z_][\w-]*)\s*=\s*(?:"([^"]*)"|\{([^}]*)\})/g)].map(
    ([, key, str, expr]) => `${/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)}: ${str !== undefined ? JSON.stringify(str) : expr.trim()}`,
  );
  return entries.length ? `{ ${entries.join(", ")} }` : "null";
}
